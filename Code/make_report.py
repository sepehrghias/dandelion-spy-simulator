"""
make_report.py
==============
Data-driven report generator: reads results/*.csv and produces a complete
Persian report (Report.md) with filled-in tables, figure references, methodology
and analysis. Report.md can then be converted to PDF.

NOTE: the report *body* text is intentionally Persian (the deliverable report is
in Persian); only the code comments/docstrings here are in English.

Run:  python make_report.py     (after  python main.py all)
"""

from __future__ import annotations

import csv
import os
from typing import Dict, List

import config

R = config.RESULTS_DIR
OUT = os.path.join(config.PROJECT_DIR, "Report.md")


def _read(name: str) -> List[dict]:
    path = os.path.join(R, name)
    if not os.path.exists(path):
        return []
    with open(path, encoding="utf-8-sig") as f:
        return list(csv.DictReader(f))


def _md_table(rows: List[dict], cols: List[str], headers: List[str]) -> str:
    if not rows:
        return "_داده‌ای موجود نیست (ابتدا `python main.py all` را اجرا کنید)._\n"
    out = ["| " + " | ".join(headers) + " |",
           "| " + " | ".join(["---"] * len(headers)) + " |"]
    for r in rows:
        out.append("| " + " | ".join(str(r.get(c, "")) for c in cols) + " |")
    return "\n".join(out) + "\n"


def _fig(name: str, caption: str) -> str:
    return f"\n![{caption}](figures/{name})\n\n*شکل: {caption}*\n"


def build() -> str:
    p1 = _read("phase1_diffusion.csv")
    p2 = _read("phase2_spy_sweep.csv")
    p3s = _read("phase3_dandelion_stats.csv")
    p4s = _read("phase4_attack_stats.csv")
    p5s = _read("phase5_delay_stats.csv")
    summ = _read("summary_scores.csv")
    clus = _read("topology_clusters.csv")

    # n* from Phase 2
    n_star = "?"
    if p2:
        n_star = max(p2, key=lambda r: float(r["score_adv_proposed"]))["n_spies"]

    S = []
    A = S.append

    A("# گزارش پروژه: قاصدک در برابر جاسوس\n")
    A("### شبیه‌سازی پویا و چالش حریم خصوصی در شبکه — درس شبکه‌های کامپیوتری (۴۰۴۴۳)\n")
    A("\n---\n")

    # ------------------------------------------------------------------ abstract
    A("## چکیده\n")
    A("یک شبکهٔ فضاییِ کلاستری با گره‌های مستقل (هر گره روی یک پورت UDP جداگانه) "
      "پیاده‌سازی شد و دو پروتکل انتشار روی آن اجرا گردید: **پخش عمومی پایه** و "
      "**Dandelion**. سپس یک **مهاجمِ منبع‌یاب** طراحی شد که با رشوه‌دادن به بخشی "
      "از گره‌ها (حداکثر ۳۰٪) تلاش می‌کند مبدأ هر بسته را حدس بزند. نتایج نشان "
      "می‌دهد که Dandelion در مقادیر بالای p حریم خصوصی به‌مراتب بهتری فراهم "
      "می‌کند (به بهای کاهش قابلیت اطمینان و افزایش زمان پوشش)، و حملهٔ پیشنهادیِ "
      "بیزیِ کالیبره‌شده با مونت‌کارلو در همهٔ حالت‌ها از حملهٔ پایه بهتر عمل "
      "می‌کند.\n")
    if summ:
        A("\n**جدول خلاصهٔ امتیازها:**\n")
        A(_md_table(summ, ["phase", "p", "n_bribed", "accuracy", "score_adv",
                           "T80_sec", "reach_rate", "score_honest",
                           "eff_score_honest"],
                    ["فاز", "p", "#جاسوس", "دقت", "Score_adv", "T80% (s)",
                     "نرخ تحویل", "Score_honest", "Score_honest مؤثر"]))
        A("\n> **نکتهٔ مهم دربارهٔ Score_honest:** طبق فرمول صورت پروژه، T80% تنها "
          "روی بسته‌هایی محاسبه می‌شود که به آستانهٔ ۸۰٪ رسیده‌اند؛ بنابراین این "
          "معیار برای تحویل‌نشدنِ بسته‌ها جریمه‌ای در نظر نمی‌گیرد. به همین دلیل "
          "p=۰.۹ بالاترین Score_honest را می‌گیرد، حال آنکه نرخ تحویل آن پایین "
          "است. ستون «Score_honest مؤثر» = Score_honest × نرخ تحویل، این کاستی "
          "را جبران می‌کند و تصویر واقعی‌تری از سودمندی شبکه می‌دهد.\n")
    A("\n---\n")

    # --------------------------------------------------- Part 1: system architecture
    A("## ۱) معماری سیستم و قوانین شبکه\n")
    A("### ۱-۱) معماری گره\n")
    A("هر گره یک واحد مستقل با حالت‌های زیر است (پیاده‌سازی در `protocol.py` و "
      "`udp_runtime.py`):\n")
    A("- **NodeID**: شناسهٔ یکتا با فرمت UUID، مستقل از آدرس شبکه.\n")
    A("- **SelfAddr**: آدرس `ip:port` روی `127.0.0.1` (هر گره یک پورت UDP مستقل).\n")
    A("- **Peer List**: فهرست همسایگان مستقیم به‌همراه «آخرین زمان مشاهده» "
      "(`peer_last_seen`). درجهٔ گره‌ها در بازهٔ ۲ تا ۴ کنترل می‌شود و هیچ گره "
      "بدون همسایه نمی‌ماند.\n")
    A("- **Seen Set**: مجموعهٔ `PacketID`های دیده‌شده برای حذف نسخه‌های تکراری.\n")
    A("- **ساختار بسته**: هر بستهٔ سطح شبکه تنها شامل `PacketID` و وضعیت "
      "(`Stem`/`Fluff`) است. شناسهٔ واقعی مبدأ و زمان ایجاد **فقط در لاگ مرجع "
      "شبیه‌ساز** (خارج از باند) ثبت می‌شوند و در محتوای بستهٔ روی سیم قرار "
      "نمی‌گیرند.\n")
    A("- **مدل زمان**: ساعت‌ها همگام و تأخیر پردازش داخلی صفر؛ تنها در فاز ۵ "
      "جاسوس‌ها مجاز به تأخیر عمدی‌اند.\n")
    A("\n> **هم‌زمانی:** هر گره در یک **نخ (Thread) مستقل** با **حلقهٔ asyncio** "
      "اجرا می‌شود و روی یک **سوکت UDP مستقل** می‌شنود؛ بنابراین شرط «شبیه‌سازیِ "
      "کاملاً هم‌زمان با Multi-threading/Async I/O و پورت UDP مستقل برای هر گره» "
      "برآورده می‌شود.\n")

    A("\n### ۱-۲) روش تولید توپولوژی و کلاسترها\n")
    A("گره‌ها روی صفحهٔ ۱۰۰۰×۱۰۰۰ جانمایی می‌شوند: حدود ۷۸٪ گره‌ها با توزیع "
      "**گاوسی** حول ۴ تا ۶ مرکز کلاستر (با انحراف معیار "
      f"σ={config.CLUSTER_SIGMA:g} و حداقل فاصلهٔ مراکز "
      f"{config.CLUSTER_MIN_CENTER_DIST:g}) و بقیه به‌صورت یکنواخت پراکنده "
      "می‌شوند. یال‌ها با رشد حریصانهٔ نزدیک‌ترین زوج‌ها تا درجهٔ هدف ۳ (سقف ۴) "
      "ساخته می‌شوند.\n")
    A("\n**اتصال چندگانه و همبندی:** پس از ساخت، (۱) مؤلفه‌های ناهمبند با کوتاه‌ترین "
      "یال بین‌مؤلفه‌ای وصل می‌شوند تا شبکه همبند شود، و (۲) برای هر کلاستر تضمین "
      "می‌شود دست‌کم **دو لینک مستقل به دو گرهٔ بیرونیِ متمایز** داشته باشد تا "
      "مسیر جایگزین وجود داشته باشد. اعتبارسنجی نهایی (`Topology.validate`) همبندی، "
      "حداقل درجه و شرط اتصال چندگانه را بررسی می‌کند.\n")
    if clus:
        A("\n**اثبات اتصال چندگانهٔ کلاسترها (بذر نمونه):**\n")
        A(_md_table(clus, ["cluster", "size", "external_independent_links", "members"],
                    ["کلاستر", "اندازه", "لینک‌های مستقل بیرونی", "اعضا"]))
    A(_fig("topology.png", "توپولوژی نمونه؛ رنگ‌ها کلاسترها و × قرمز گره‌های جاسوس."))

    A("\n### ۱-۳) فرمول تأخیر لینک\n")
    A("تأخیر پایه = فاصلهٔ اقلیدسی × ۱ms/واحد؛ و جیتر ۲۰٪:\n")
    A("\n> **Delay_Total = Delay_Base + U(−0.2·Delay_Base, +0.2·Delay_Base)**\n")
    A("\nجیتر برای «هر ارسال» به‌صورت مستقل نمونه‌گیری می‌شود "
      "(`protocol.transit_delay`).\n")

    A("\n### ۱-۴) مدل مهاجم\n")
    A("- مهاجم **تأخیر پایهٔ همهٔ لینک‌ها و ساختار گراف** را می‌داند اما دیدِ "
      "سراسری ندارد و تنها بسته‌هایی را می‌بیند که به گره‌های جاسوسش می‌رسند.\n")
    A("- **ممنوعیت حذف بسته**: جاسوس‌ها بسته را حذف/مسدود نمی‌کنند و طبق پروتکل "
      "بازپخش می‌کنند؛ تنها در فاز ۵ می‌توانند پیش از بازپخش تأخیر بیفزایند.\n")
    A("- **انتخاب جاسوس**: بر پایهٔ **مرکزیت میانیِ وزن‌دار** (Brandes روی "
      "کوتاه‌ترین‌مسیرهای تأخیری)؛ گره‌های پرمرکزیت بسته‌ها را زودتر و از جهات "
      "بیشتری می‌بینند. مجموعه‌ها «تودرتو»اند تا پویش تعداد جاسوس منصفانه باشد.\n")

    A("\n---\n")

    # --------------------------------------------------- Part 2: phases
    A("## ۲) فازهای عملیاتی و نتایج\n")

    A("### فاز ۱ — پخش عمومی پایه\n")
    A("هر گره پس از نخستین دریافت، بسته را به همهٔ همسایگانش بازپخش می‌کند و "
      "نسخه‌های تکراری با Seen Set حذف می‌شوند. انتشار همیشه به پوشش کامل "
      "می‌رسد.\n")
    if p1:
        A(_md_table(p1, ["seed", "coverage", "reach80", "T80_sec"],
                    ["بذر", "پوشش", "reach-80%", "T80% (s)"]))
    A(_fig("phase1_coverage_curve.png",
           "منحنی پوشش شبکه بر حسب زمان در پخش عمومی (هر خط یک بسته)."))

    A("\n### فاز ۲ — حمله به پخش عمومی و تعیین تعداد بهینهٔ جاسوس\n")
    A("دو حمله پیاده شد: **پایه «اولین جاسوس مشاهده‌کننده»** (حدس = فرستندهٔ "
      "نخستین مشاهدهٔ جاسوس) و **پیشنهادیِ بیزیِ مونت‌کارلو** (شرح در فاز ۴). "
      "چون `Score_adv = دقت ÷ تعداد جاسوس`، افزودن جاسوس شدیداً جریمه می‌شود؛ "
      f"لذا تعداد بهینه کوچک است: **n\\* = {n_star}**.\n")
    if p2:
        A(_md_table(p2, ["n_spies", "acc_baseline", "acc_proposed",
                         "score_adv_baseline", "score_adv_proposed"],
                    ["#جاسوس", "دقت پایه", "دقت پیشنهادی", "Score_adv پایه",
                     "Score_adv پیشنهادی"]))
    A(_fig("phase2_spy_sweep.png",
           "چپ: دقت بر حسب تعداد جاسوس؛ راست: Score_adv و نقطهٔ بهینه n*."))

    A("\n### فاز ۳ — Dandelion و پویش پارامتر p\n")
    A("گره مبدأ بسته را Stem می‌سازد و فقط به یک همسایهٔ تصادفی می‌فرستد؛ هر "
      "گیرنده با احتمال p ساقه را ادامه می‌دهد (به همسایه‌ای جز فرستندهٔ قبلی) و "
      "با احتمال ۱−p وارد Fluff می‌شود و به همه بازپخش می‌کند. نتایج برای "
      "p∈{۰.۹، ۰.۵، ۰.۱} روی چند بذر (میانگین/میانه/انحراف‌معیار):\n")
    if p3s:
        A(_md_table(p3s, ["p", "metric", "mean", "median", "std", "n"],
                    ["p", "معیار", "میانگین", "میانه", "انحراف‌معیار", "n"]))
    A("\n**تحلیل:** با افزایش p ساقه طولانی‌تر می‌شود؛ این حریم خصوصی را بالا "
      "می‌برد اما احتمال «بن‌بست ساقه» (برخورد به گرهٔ دیده‌شده پیش از Fluff) را "
      "نیز زیاد می‌کند؛ در نتیجه در p بالا نرخ رسیدن به ۸۰٪ گره‌ها و پوشش کاهش و "
      "زمان پوشش افزایش می‌یابد. این یک مصالحهٔ ذاتیِ حریم‌خصوصی/قابلیت‌اطمینان "
      "است.\n")
    A(_fig("phase3_psweep.png",
           "پویش پارامتر p: زمان پوشش، نرخ اطمینان و طول ساقه (میانگین ± انحراف‌معیار)."))

    A("\n### فاز ۴ — حملهٔ پیشرفته به Dandelion\n")
    A("چون در فاز ساقه مسیر پنهان است، حملهٔ مبتنی بر زمان (TDOA) کارا نیست "
      "(مکان‌یابی نقطهٔ Fluff می‌کند نه مبدأ). حملهٔ پیشنهادی **بیزیِ کالیبره با "
      "مونت‌کارلو** است: مهاجم با دانشِ خود (گراف، p، مجموعهٔ جاسوس) هزاران انتشار "
      "Dandelion شبیه‌سازی می‌کند و توزیع **امضای مشاهده** = «(اولین جاسوس، "
      "فرستنده، وضعیت Stem/Fluff)» را به‌ازای هر مبدأ می‌آموزد؛ سپس برای بستهٔ "
      "واقعی، مبدأی با بیشترین درست‌نمایی را برمی‌گزیند.\n")
    if p4s:
        A(_md_table(p4s, ["p", "method", "mean", "median", "std"],
                    ["p", "روش", "میانگین دقت", "میانه", "انحراف‌معیار"]))
    A("\n**تحلیل:** روش پیشنهادی در هر سه مقدار p از پایه و از TDOA بهتر است و "
      "بیشترین برتری را در p پایین دارد (ساقهٔ کوتاه‌تر ⇒ فرستندهٔ نخستین مشاهده "
      "نزدیک به مبدأ). در p=۰.۹ به‌دلیل ساقهٔ طولانیِ پنهان، دقتِ هر دو روش پایین "
      "است — یعنی Dandelion در p بالا واقعاً از مبدأ محافظت می‌کند.\n")
    A(_fig("phase4_attack.png",
           "دقت حمله روی Dandelion برای سه روش و سه مقدار p (میانگین ± انحراف‌معیار)."))

    A("\n### فاز ۵ — تأخیر عمدی جاسوس‌ها\n")
    A("جاسوس‌ها می‌توانند پیش از بازپخش، تأخیری تا سقف «تأخیر پایهٔ همان لینک» "
      "بیفزایند (بدون حذف یا نگه‌داری نامحدود). مهاجم چون سیاست تأخیر خود را "
      "می‌داند، مدل مونت‌کارلویش را با همان سیاست کالیبره می‌کند.\n")
    if p5s:
        A(_md_table(p5s, ["p", "policy", "metric", "mean", "median", "std"],
                    ["p", "سیاست", "معیار", "میانگین", "میانه", "انحراف‌معیار"]))
    A("\n**تحلیل:** تأخیر عمدی **زمان پوشش (T80%) را به‌وضوح افزایش می‌دهد** "
      "(زیان برای شبکهٔ درستکار). اثر آن بر دقت مهاجم کوچک است؛ چون جاسوس تأخیر "
      "را روی خروجی خود اعمال می‌کند نه روی زمانِ نخستین مشاهدهٔ خودش، امضای "
      "«اولین جاسوس/فرستنده» تقریباً حفظ می‌شود. جزئیات عددی در جدول بالا و شکل "
      "زیر آمده است.\n")
    A(_fig("phase5_delay.png",
           "اثر تأخیر عمدی جاسوس بر دقت مهاجم (چپ) و بر زمان پوشش T80% (راست)."))

    A("\n---\n")

    # --------------------------------------------------- Part 3: metrics
    A("## ۳) معیارهای ارزیابی\n")
    A("**امتیاز مهاجم:**  Score_adv = Accuracy / (تعداد گره‌های رشوه‌گرفته)\n")
    A("\n**امتیاز شبکهٔ درستکار:**  Score_honest = (1 / T80%) × (1 − Adversary "
      "Detection Rate)\n")
    A("\nکه در آن T80% میانگین زمان (ثانیه) رسیدن بسته به ۸۰٪ گره‌ها (روی "
      "بسته‌هایی که به این آستانه رسیده‌اند) و Adversary Detection Rate همان دقت "
      "حدس مهاجم است. جدول خلاصهٔ بخش ۰ مقادیر نهایی را گرد می‌آورد.\n")

    A("\n---\n")
    A("## ۴) بازتولیدپذیری و بذرها\n")
    A("مقدار `Random Seed` در همه‌جا صریح و ثبت‌شده است. برای هر بذر آزمایش یک "
      "توپولوژی، یک مجموعهٔ جاسوس و یک مجموعهٔ مبدأ بسته ساخته و در همهٔ فازها و "
      f"مقادیر p ثابت نگه داشته می‌شود؛ آمار روی {config.N_SEEDS} بذر مستقل "
      "(میانگین/میانه/انحراف‌معیار) گزارش شده است. کل آزمایش‌ها با فرمان "
      "`python main.py all` به‌طور کامل بازتولید می‌شوند.\n")
    A("\n---\n")
    A("## ۵) نتیجه‌گیری\n")
    A("- توپولوژیِ کلاستریِ همبند با اتصال چندگانه تولید و اثبات شد.\n")
    A("- Dandelion یک اهرم تنظیم‌پذیر میان حریم خصوصی و قابلیت اطمینان است: "
      "p بالاتر ⇒ حریم خصوصی بیشتر، اطمینان کمتر و زمان پوشش بیشتر.\n")
    A("- حملهٔ پیشنهادیِ بیزیِ مونت‌کارلو به‌طور پیوسته از حملهٔ پایه و از TDOA "
      "بهتر است، به‌ویژه در p پایین.\n")
    A("- تأخیر عمدی جاسوس بیش از آنکه به مهاجم کمک کند، به شبکهٔ درستکار (از طریق "
      "افزایش T80%) آسیب می‌زند.\n")

    return "\n".join(S)


if __name__ == "__main__":
    config.ensure_dirs()
    md = build()
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(md)
    print(f"report generated: {OUT}")
    print("for PDF: open the file in VS Code/Typora and Export to PDF,")
    print("or run:  python make_pdf.py  (renders via headless Edge/Chrome).")
